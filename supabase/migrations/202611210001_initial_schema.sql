create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'profiles', 'portfolio_projects', 'products',
    'product_demos', 'job_openings', 'career_applications'
  ]
  loop
    execute format('drop trigger if exists set_updated_at on public.%I', table_name);
    execute format(
      'create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()',
      table_name
    );
  end loop;
end;
$$;

create or replace function public.notify_admin_submission()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  notification_type text;
  notification_title text;
  notification_message text;
begin
  if tg_table_name = 'project_enquiries' then
    notification_type := 'enquiry';
    notification_title := 'New project enquiry';
    notification_message := 'A new project enquiry was received.';
  elsif tg_table_name = 'contact_messages' then
    notification_type := 'contact';
    notification_title := 'New contact message';
    notification_message := 'A new contact message was received.';
  else
    notification_type := 'job_application';
    notification_title := 'New job application';
    notification_message := 'A new job application was received.';
  end if;

  insert into public.notifications (type, title, message, entity_type, entity_id)
  values (notification_type, notification_title, notification_message, tg_table_name, new.id::text);
  return new;
end;
$$;

